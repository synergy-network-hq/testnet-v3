use std::path::PathBuf;

use serde::{Deserialize, Serialize};
use synergy_protocol_types::NodeRole;

use crate::{
    ConsensusConfiguration, EtdagConfiguration, NetworkConfiguration, P2pConfiguration,
    RpcConfiguration, StorageConfiguration, TelemetryConfiguration, UpdateConfiguration,
    VpnConfiguration,
};

pub const CONFIG_SCHEMA_VERSION: u16 = 1;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NodeConfiguration {
    pub schema_version: u16,
    pub node_name: String,
    pub role: NodeRole,
    pub chain_id: u64,
    pub network_id: String,
    /// Signed new-network context used to bind transport, sync, and PoSy
    /// callers to one chain incarnation. Legacy Genesis formats are excluded.
    pub manifest_path: PathBuf,
    /// Selected signed Genesis; CLI preflight/start require authentication against
    /// consensus.authority_trust_key_path before using any network context.
    #[serde(default)]
    pub genesis_path: Option<PathBuf>,
    pub public_identity_path: PathBuf,
    /// Optional governed Aegis identity-to-public-key bindings for P2P authentication.
    #[serde(default)]
    pub aegis_key_bindings_path: Option<PathBuf>,
    /// Provisioned local P2P identity signing key; never generated by the node.
    #[serde(default)]
    pub aegis_signing_key_path: Option<PathBuf>,
    /// Explicit authenticated native APQE provider set; never discovered from the environment.
    #[serde(default)]
    pub aegis_provider: Option<ApqeProviderConfiguration>,
    /// Explicit isolated development canary transport; never a production release approval.
    #[serde(default)]
    pub apqe_transport: Option<ApqeTransportConfiguration>,
    pub admin_socket_path: PathBuf,
    #[serde(default)]
    pub network: NetworkConfiguration,
    #[serde(default)]
    pub p2p: P2pConfiguration,
    #[serde(default)]
    pub consensus: ConsensusConfiguration,
    #[serde(default)]
    pub etdag: EtdagConfiguration,
    pub storage: StorageConfiguration,
    #[serde(default)]
    pub rpc: RpcConfiguration,
    #[serde(default)]
    pub telemetry: TelemetryConfiguration,
    #[serde(default)]
    pub update: UpdateConfiguration,
    #[serde(default)]
    pub vpn: VpnConfiguration,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ApqeProviderConfiguration {
    pub report_path: PathBuf,
    pub authenticated_report_sha256: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ApqeTransportProfile {
    EngineeringCanaryPqVsessionV1,
}
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ApqeTransportConfiguration {
    pub profile: ApqeTransportProfile,
    pub registry_path: PathBuf,
    pub registry_trust_key_path: PathBuf,
    /// Immutable operator-approved SHA-256 fingerprint, supplied out of band.
    pub registry_trust_key_sha256: String,
    /// Immutable operator-approved Genesis authority fingerprint.
    pub genesis_trust_key_sha256: String,
    pub enrollment_path: PathBuf,
    pub custody_path: PathBuf,
    /// Private bounded file, read into a zeroizing allocation; never logged.
    pub custody_unlock_path: PathBuf,
}
