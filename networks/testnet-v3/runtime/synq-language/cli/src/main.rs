fn compile_source(path: &Path) -> Result<CompiledSource, String> {
    let source = fs::read_to_string(path)
        .map_err(|e| format!("Failed to read source file {}: {e}", path.display()))?;
    let artifact_config = load_artifact_config(path)?;
    let (_version_req, ast) = compiler::parse(&source)
        .map_err(|e| format!("Failed to parse source file {}: {e}", path.display()))?;
    compiler::analyze(&ast).map_err(|errors| format_semantic_errors(path, &errors))?;

    let codegen = compiler::CodeGenerator::new();
    let bytecode = codegen
        .generate_stateful(&ast)
        .map_err(|e| format!("Failed to generate bytecode: {e}"))?;

    let sol_gen = compiler::SolidityGenerator::new();
    let solidity_code = sol_gen
        .generate(&ast)
        .map_err(|e| format!("Failed to generate Solidity code: {e}"))?;

    let bundle =
        compiler::ArtifactBundle::generate_with_config(&source, &ast, bytecode, &artifact_config)
            .map_err(|e| format!("Failed to generate canonical artifacts: {e}"))?;

    Ok(CompiledSource {
        bundle,
        solidity_code,
    })
}

fn load_artifact_config(source_path: &Path) -> Result<compiler::ArtifactConfig, String> {
    let Some(config_path) = find_synq_toml(source_path) else {
        return Ok(compiler::ArtifactConfig::testnet_1266());
    };

    let contents = fs::read_to_string(&config_path)
        .map_err(|e| format!("Failed to read config {}: {e}", config_path.display()))?;
    let config: SynqProjectConfig = toml::from_str(&contents)
        .map_err(|e| format!("Failed to parse config {}: {e}", config_path.display()))?;

    config.to_artifact_config(&config_path)
}

fn find_synq_toml(source_path: &Path) -> Option<PathBuf> {
    let mut current = if source_path.is_dir() {
        source_path.to_path_buf()
    } else {
        source_path.parent()?.to_path_buf()
    };

    loop {
        let candidate = current.join("synq.toml");
        if candidate.exists() {
            return Some(candidate);
        }
        if !current.pop() {
            return None;
        }
    }
}

impl SynqProjectConfig {
    fn to_artifact_config(&self, config_path: &Path) -> Result<compiler::ArtifactConfig, String> {
        let package = self
            .package
            .as_ref()
            .ok_or_else(|| format!("Config {} is missing [package]", config_path.display()))?;
        package.validate(config_path)?;

        let compiler_config = self
            .compiler
            .as_ref()
            .ok_or_else(|| format!("Config {} is missing [compiler]", config_path.display()))?;
        compiler_config.validate(config_path)?;

        let network = self
            .network
            .as_ref()
            .ok_or_else(|| format!("Config {} is missing [network]", config_path.display()))?;
        network.validate(config_path)?;

        let security = self
            .security
            .as_ref()
            .ok_or_else(|| format!("Config {} is missing [security]", config_path.display()))?;
        security.validate(config_path)?;

        Ok(compiler::ArtifactConfig {
            bytecode_version: compiler_config.bytecode_version,
            required_aivm_version: compiler_config.target_aivm_version.clone(),
            required_chain_id: network.chain_id,
            required_network_id: network.network_id.clone(),
            required_signature_algorithm: security.signature_algorithm.clone(),
            security_policy: compiler::artifacts::SYNQ_TESTNET_SECURITY_POLICY.to_string(),
        })
    }
}

