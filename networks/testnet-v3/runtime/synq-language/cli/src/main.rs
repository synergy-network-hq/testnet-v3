fn main() {
    let cli = Cli::parse();

    let result = match &cli.command {
        Commands::Init { name, force } => init_project(name, *force),
        Commands::Build { path } => build(path),
        Commands::Check { path } => check(path),
        Commands::Abi { path, output } => emit_abi(path, output.as_deref()),
        Commands::Manifest { path, output } => emit_manifest(path, output.as_deref()),
        Commands::Keygen {
            algorithm,
            network,
            out_dir,
            name,
            force,
        } => keygen(algorithm, network, out_dir, name, *force),
        Commands::SignDeploy {
            bytecode,
            manifest,
            abi,
            private_key,
            args,
            output,
            chain,
            network,
            nonce,
            not_before_unix,
            expiration_unix,
            force,
        } => sign_deploy(SignDeployOptions {
            bytecode,
            manifest,
            abi,
            private_key,
            args: args.as_deref(),
            output,
            chain: *chain,
            network,
            nonce: *nonce,
            not_before_unix: *not_before_unix,
            expiration_unix: *expiration_unix,
            force: *force,
        }),
        Commands::VerifyDeploy {
            envelope,
            chain,
            network,
            now_unix,
        } => verify_deploy(envelope, *chain, network, *now_unix),
        Commands::SignCall {
            contract,
            method,
            abi,
            manifest,
            private_key,
            args,
            output,
            chain,
            network,
            nonce,
            not_before_unix,
            expiration_unix,
            force,
        } => sign_call(SignCallOptions {
            contract,
            method,
            abi,
            manifest,
            private_key,
            args: args.as_deref(),
            output,
            chain: *chain,
            network,
            nonce: *nonce,
            not_before_unix: *not_before_unix,
            expiration_unix: *expiration_unix,
            force: *force,
        }),
        Commands::VerifyCall {
            envelope,
            chain,
            network,
            now_unix,
        } => verify_call(envelope, *chain, network, *now_unix),
        Commands::Simulate { path } => simulate(path),
        Commands::Compile { path } => compile(path),
        Commands::Run { path } => run(path),
        Commands::Verify {
            source,
            bytecode,
            run,
        } => verify(source, bytecode, *run),
    };

    if let Err(err) = result {
        eprintln!("Error: {err}");
        process::exit(1);
    }
}

fn init_project(project_dir: &Path, force: bool) -> Result<(), String> {
    let contracts_dir = project_dir.join("contracts");
    let tests_dir = project_dir.join("tests");
    let scripts_dir = project_dir.join("scripts");
    fs::create_dir_all(&contracts_dir).map_err(|e| {
        format!(
            "Failed to create contracts directory {}: {e}",
            contracts_dir.display()
        )
    })?;
    fs::create_dir_all(&tests_dir).map_err(|e| {
        format!(
            "Failed to create tests directory {}: {e}",
            tests_dir.display()
        )
    })?;
    fs::create_dir_all(&scripts_dir).map_err(|e| {
        format!(
            "Failed to create scripts directory {}: {e}",
            scripts_dir.display()
        )
    })?;

    write_template(&project_dir.join("synq.toml"), SYNQ_TOML_TEMPLATE, force)?;
    write_template(&contracts_dir.join("Counter.synq"), COUNTER_TEMPLATE, force)?;
    write_template(&project_dir.join(".gitignore"), GITIGNORE_TEMPLATE, force)?;
    write_template(&tests_dir.join(".gitkeep"), "", force)?;
    write_template(
        &scripts_dir.join("deploy-local-demo.sh"),
        DEPLOY_LOCAL_DEMO_TEMPLATE,
        force,
    )?;

    println!("✓ Created SynQ project: {}", project_dir.display());
    println!(
        "✓ Contract: {}",
        contracts_dir.join("Counter.synq").display()
    );
    println!("✓ Config: {}", project_dir.join("synq.toml").display());
    println!(
        "Next: synq build {}",
        contracts_dir.join("Counter.synq").display()
    );
    Ok(())
}

fn write_template(path: &Path, contents: &str, force: bool) -> Result<(), String> {
    if path.exists() && !force {
        return Err(format!(
            "Refusing to overwrite existing file {}. Re-run with --force to replace scaffold files.",
            path.display()
        ));
    }
    fs::write(path, contents).map_err(|e| format!("Failed to write {}: {e}", path.display()))
}

fn compile(path: &Path) -> Result<(), String> {
    println!("Compiling: {}", path.display());
    let compiled = compile_source(path)?;

    // Generate .synq bytecode
    let (synq_path, sol_path) = derive_output_paths(path);
    fs::write(&synq_path, &compiled.bundle.bytecode)
        .map_err(|e| format!("Failed to write .synq file: {e}"))?;
    println!("✓ Generated: {}", synq_path.display());

    // Generate .sol Solidity code
    fs::write(&sol_path, &compiled.solidity_code)
        .map_err(|e| format!("Failed to write .sol file: {e}"))?;
    println!("✓ Generated: {}", sol_path.display());
    println!("{}", compiler::SOLIDITY_COMPATIBILITY_WARNING);

    println!("Compilation complete!");
    Ok(())
}

fn check(path: &Path) -> Result<(), String> {
    let compiled = compile_source(path)?;
    println!("✓ Check succeeded: {}", path.display());
    println!("contract={}", compiled.bundle.abi.contract);
    println!("bytecode_hash={}", compiled.bundle.hashes.bytecode_hash);
    println!("abi_hash={}", compiled.bundle.hashes.abi_hash);
    println!("manifest_hash={}", compiled.bundle.hashes.manifest_hash);
    Ok(())
}

fn build(path: &Path) -> Result<(), String> {
    println!("Building canonical SynQ artifacts: {}", path.display());
    let compiled = compile_source(path)?;
    let output = derive_build_output_paths(path);

    fs::write(&output.bytecode, &compiled.bundle.bytecode)
        .map_err(|e| format!("Failed to write bytecode artifact: {e}"))?;
    fs::write(&output.abi, compiled.bundle.abi_json()?)
        .map_err(|e| format!("Failed to write ABI artifact: {e}"))?;
    fs::write(&output.manifest, compiled.bundle.manifest_json()?)
        .map_err(|e| format!("Failed to write manifest artifact: {e}"))?;
    fs::write(&output.solidity_compatibility, &compiled.solidity_code)
        .map_err(|e| format!("Failed to write Solidity compatibility artifact: {e}"))?;

    println!("✓ Bytecode: {}", output.bytecode.display());
    println!("✓ ABI: {}", output.abi.display());
    println!("✓ Manifest: {}", output.manifest.display());
    println!(
        "✓ Solidity compatibility output: {}",
        output.solidity_compatibility.display()
    );
    println!("{}", compiler::SOLIDITY_COMPATIBILITY_WARNING);
    println!(
        "bytecode_hash={}\nabi_hash={}\nmanifest_hash={}",
        compiled.bundle.hashes.bytecode_hash,
        compiled.bundle.hashes.abi_hash,
        compiled.bundle.hashes.manifest_hash
    );
    println!("Build complete!");
    Ok(())
}

fn emit_abi(path: &Path, output: Option<&Path>) -> Result<(), String> {
    let compiled = compile_source(path)?;
    write_or_print(output, &compiled.bundle.abi_json()?, "ABI")
}

fn emit_manifest(path: &Path, output: Option<&Path>) -> Result<(), String> {
    let compiled = compile_source(path)?;
    write_or_print(output, &compiled.bundle.manifest_json()?, "manifest")
}

