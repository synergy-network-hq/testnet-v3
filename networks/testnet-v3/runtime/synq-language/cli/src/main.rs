fn validate_account_domain_algorithm(algorithm: &str) -> Result<(), String> {
    let normalized = algorithm
        .chars()
        .filter(|ch| *ch != '-' && *ch != '_')
        .flat_map(|ch| ch.to_lowercase())
        .collect::<String>();
    if normalized == "mldsa87" {
        Ok(())
    } else {
        Err(format!(
            "Unsupported signature algorithm `{algorithm}`; launch policy requires the account-domain algorithm ML-DSA-87"
        ))
    }
}

fn normalize_cli_network(chain_id: u64, network: &str) -> Result<String, String> {
    if chain_id != compiler::artifacts::SYNQ_TESTNET_CHAIN_ID {
        return Err(format!(
            "Unsupported chain_id `{chain_id}`; SynQ deploy payloads are currently bound to chain_id `{}`",
            compiler::artifacts::SYNQ_TESTNET_CHAIN_ID
        ));
    }

    match network {
        "testnet" | compiler::artifacts::SYNQ_TESTNET_NETWORK_ID | "synergy-testnet-v3" => {
            Ok(compiler::artifacts::SYNQ_TESTNET_NETWORK_ID.to_string())
        }
        other => Err(format!(
            "Unsupported network `{other}`; expected `testnet`, `synergy-testnet`, or chain-1266 alias `synergy-testnet-v3`"
        )),
    }
}

fn write_json_file<T: Serialize>(
    path: &Path,
    value: &T,
    force: bool,
    private: bool,
) -> Result<(), String> {
    if path.exists() && !force {
        return Err(format!(
            "Refusing to overwrite existing file {}. Re-run with --force to replace it.",
            path.display()
        ));
    }
    let bytes = serde_json::to_vec_pretty(value)
        .map_err(|e| format!("Failed to encode JSON for {}: {e}", path.display()))?;
    fs::write(path, bytes).map_err(|e| format!("Failed to write {}: {e}", path.display()))?;
    if private {
        set_private_file_permissions(path)?;
    }
    Ok(())
}

#[cfg(unix)]
fn set_private_file_permissions(path: &Path) -> Result<(), String> {
    use std::os::unix::fs::PermissionsExt;

    let mut permissions = fs::metadata(path)
        .map_err(|e| format!("Failed to inspect {} permissions: {e}", path.display()))?
        .permissions();
    permissions.set_mode(0o600);
    fs::set_permissions(path, permissions)
        .map_err(|e| format!("Failed to restrict {} permissions: {e}", path.display()))
}

#[cfg(not(unix))]
fn set_private_file_permissions(_path: &Path) -> Result<(), String> {
    Ok(())
}

fn read_private_key(path: &Path) -> Result<SynqPrivateKeyFile, String> {
    let bytes =
        fs::read(path).map_err(|e| format!("Failed to read key {}: {e}", path.display()))?;
    let key: SynqPrivateKeyFile = serde_json::from_slice(&bytes)
        .map_err(|e| format!("Failed to parse key {}: {e}", path.display()))?;
    if key.version != 1 {
        return Err(format!(
            "Unsupported key file version `{}` in {}",
            key.version,
            path.display()
        ));
    }
    Ok(key)
}

fn validate_manifest_for_signing(
    manifest_bytes: &[u8],
    bytecode_hash: &[u8; 32],
    abi_hash: &[u8; 32],
    chain_id: u64,
    network_id: &str,
) -> Result<(), String> {
    let manifest: serde_json::Value = serde_json::from_slice(manifest_bytes)
        .map_err(|e| format!("Failed to parse manifest JSON: {e}"))?;
    expect_manifest_hex(&manifest, "bytecode_hash", bytecode_hash)?;
    expect_manifest_hex(&manifest, "abi_hash", abi_hash)?;

    let manifest_chain = manifest
        .get("required_chain_id")
        .and_then(serde_json::Value::as_u64)
        .ok_or_else(|| "Manifest missing numeric required_chain_id".to_string())?;
    if manifest_chain != chain_id {
        return Err(format!(
            "Manifest required_chain_id `{manifest_chain}` does not match signing chain_id `{chain_id}`"
        ));
    }

    let manifest_network = manifest
        .get("required_network_id")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| "Manifest missing string required_network_id".to_string())?;
    let normalized_manifest_network = normalize_cli_network(manifest_chain, manifest_network)?;
    if normalized_manifest_network != network_id {
        return Err(format!(
            "Manifest required_network_id `{manifest_network}` does not match signing network `{network_id}`"
        ));
    }

    let signature_algorithm = manifest
        .get("required_signature_algorithm")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| "Manifest missing string required_signature_algorithm".to_string())?;
    validate_account_domain_algorithm(signature_algorithm)?;

    Ok(())
}

fn validate_manifest_policy_for_call(
    manifest_bytes: &[u8],
    abi_hash: &[u8; 32],
    chain_id: u64,
    network_id: &str,
) -> Result<(), String> {
    let manifest: serde_json::Value = serde_json::from_slice(manifest_bytes)
        .map_err(|e| format!("Failed to parse manifest JSON: {e}"))?;
    expect_manifest_hex(&manifest, "abi_hash", abi_hash)?;

    let manifest_chain = manifest
        .get("required_chain_id")
        .and_then(serde_json::Value::as_u64)
        .ok_or_else(|| "Manifest missing numeric required_chain_id".to_string())?;
    if manifest_chain != chain_id {
        return Err(format!(
            "Manifest required_chain_id `{manifest_chain}` does not match call signing chain_id `{chain_id}`"
        ));
    }

    let manifest_network = manifest
        .get("required_network_id")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| "Manifest missing string required_network_id".to_string())?;
    let normalized_manifest_network = normalize_cli_network(manifest_chain, manifest_network)?;
    if normalized_manifest_network != network_id {
        return Err(format!(
            "Manifest required_network_id `{manifest_network}` does not match call signing network `{network_id}`"
        ));
    }

    let signature_algorithm = manifest
        .get("required_signature_algorithm")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| "Manifest missing string required_signature_algorithm".to_string())?;
    validate_account_domain_algorithm(signature_algorithm)?;
    Ok(())
}

fn method_selector_from_abi(abi_bytes: &[u8], method: &str) -> Result<[u8; 4], String> {
    let abi: serde_json::Value =
        serde_json::from_slice(abi_bytes).map_err(|e| format!("Failed to parse ABI JSON: {e}"))?;
    let methods = abi
        .get("methods")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| "ABI missing methods array".to_string())?;
    let method_json = methods
        .iter()
        .find(|entry| entry.get("name").and_then(serde_json::Value::as_str) == Some(method))
        .ok_or_else(|| format!("ABI does not contain method `{method}`"))?;

    let params = method_json
        .get("params")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| format!("ABI method `{method}` is missing params array"))?;
    if !params.is_empty() {
        return Err(format!(
            "CLI call signing currently supports no-argument methods only; `{method}` has {} parameter(s)",
            params.len()
        ));
    }

    let selector = method_json
        .get("selector")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| format!("ABI method `{method}` is missing selector"))?;
    let selector_hex = selector.strip_prefix("0x").unwrap_or(selector);
    let selector_bytes = hex::decode(selector_hex)
        .map_err(|e| format!("ABI method `{method}` has invalid selector `{selector}`: {e}"))?;
    if selector_bytes.len() != 4 {
        return Err(format!(
            "ABI method `{method}` selector `{selector}` is not 4 bytes"
        ));
    }
    let mut out = [0_u8; 4];
    out.copy_from_slice(&selector_bytes);
    Ok(out)
}

fn canonical_json_args(args: Option<&str>, label: &str) -> Result<Vec<u8>, String> {
    let normalized = args.unwrap_or("").trim();
    if normalized.is_empty() || normalized == "[]" {
        return Ok(Vec::new());
    }

    let value: serde_json::Value = serde_json::from_str(normalized)
        .map_err(|e| format!("{label} args must be valid JSON when supplied: {e}"))?;
    let array = value
        .as_array()
        .ok_or_else(|| format!("{label} args must be a JSON array"))?;
    if array.is_empty() {
        return Ok(Vec::new());
    }
    serde_json::to_vec(&value).map_err(|e| format!("Canonicalize {label} args: {e}"))
}

fn parse_synq_address(value: &str) -> Result<SynQAddress, String> {
    let raw = value.trim();
    let hex_value = raw.strip_prefix("tsynq1").unwrap_or(raw);
    let bytes = hex::decode(hex_value)
        .map_err(|e| format!("Invalid SynQ address `{value}` hex encoding: {e}"))?;
    if bytes.len() != pqsynq::address::SYNQ_ADDRESS_LEN {
        return Err(format!(
            "Invalid SynQ address `{value}` length {}; expected {} bytes",
            bytes.len(),
            pqsynq::address::SYNQ_ADDRESS_LEN
        ));
    }
    let mut out = [0_u8; pqsynq::address::SYNQ_ADDRESS_LEN];
    out.copy_from_slice(&bytes);
    Ok(SynQAddress::from_bytes(out))
}

fn expect_manifest_hex(
    manifest: &serde_json::Value,
    field: &str,
    expected: &[u8; 32],
) -> Result<(), String> {
    let actual = manifest
        .get(field)
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| format!("Manifest missing string {field}"))?;
    let expected_hex = hex::encode(expected);
    if actual == expected_hex {
        Ok(())
    } else {
        Err(format!(
            "Manifest {field} `{actual}` does not match artifact hash `{expected_hex}`"
        ))
    }
}

fn derive_output_paths(path: &Path) -> (PathBuf, PathBuf) {
    let synq_path = match path.extension().and_then(|ext| ext.to_str()) {
        Some(ext) if ext.eq_ignore_ascii_case("synq") => path.with_extension("compiled.synq"),
        _ => path.with_extension("synq"),
    };
    let sol_path = path.with_extension("sol");
    (synq_path, sol_path)
}

struct BuildOutputPaths {
    abi: PathBuf,
    bytecode: PathBuf,
    manifest: PathBuf,
    solidity_compatibility: PathBuf,
}

fn derive_build_output_paths(path: &Path) -> BuildOutputPaths {
    let (bytecode, solidity_compatibility) = derive_output_paths(path);
    BuildOutputPaths {
        abi: path.with_extension("abi.json"),
        bytecode,
        manifest: path.with_extension("manifest.json"),
        solidity_compatibility,
    }
}

fn execute_bytecode(bytecode: &[u8]) -> Result<(), String> {
    let executable = compiler::StatefulSynQExecutable::decode(bytecode).ok();
    let executable_bytes = executable
        .as_ref()
        .map(|executable| executable.legacy_quantum_vm_bytecode.as_slice())
        .unwrap_or(bytecode);
    if executable.is_some() && executable_bytes.is_empty() {
        return Err(
            "Stateful SynQ IR requires AIVM execution; no legacy QuantumVM program is available"
                .to_string(),
        );
    }
    let mut vm = quantumvm::QuantumVM::new();
    vm.load_bytecode(executable_bytes)
        .map_err(|e| format!("Failed to load bytecode: {e}"))?;
    vm.execute()
        .map_err(|e| format!("VM execution failed: {e}"))?;
    Ok(())
}

fn sha256_hex(bytes: &[u8]) -> String {
    hex::encode(sha256_array(bytes))
}

fn sha256_array(bytes: &[u8]) -> [u8; 32] {
    let digest = Sha256::digest(bytes);
    let mut out = [0_u8; 32];
    out.copy_from_slice(&digest);
    out
}

fn first_diff_index(a: &[u8], b: &[u8]) -> Option<usize> {
    let limit = a.len().min(b.len());
    for i in 0..limit {
        if a[i] != b[i] {
            return Some(i);
        }
    }
    if a.len() != b.len() {
        return Some(limit);
    }
    None
}

fn format_semantic_errors(path: &Path, errors: &[compiler::ast::SemanticError]) -> String {
    let mut out = format!("Semantic analysis failed for {}:", path.display());
    for (idx, error) in errors.iter().enumerate() {
        let location = match (error.line, error.column) {
            (Some(line), Some(column)) => format!(" [line {line}, col {column}]"),
            (Some(line), None) => format!(" [line {line}]"),
            _ => String::new(),
        };
        out.push_str(&format!("\n  {}. {}{}", idx + 1, error.message, location));
    }
    out
}
