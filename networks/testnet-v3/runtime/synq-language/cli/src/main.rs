fn sign_call(options: SignCallOptions<'_>) -> Result<(), String> {
    if options.output.exists() && !options.force {
        return Err(format!(
            "Refusing to overwrite existing envelope {}. Re-run with --force to replace it.",
            options.output.display()
        ));
    }

    let network_id = normalize_cli_network(options.chain, options.network)?;
    let key = read_private_key(options.private_key)?;
    validate_account_domain_algorithm(&key.algorithm)?;
    if key.chain_id != options.chain {
        return Err(format!(
            "Private key is bound to chain_id `{}`, but call signing requested chain_id `{}`",
            key.chain_id, options.chain
        ));
    }
    if key.network_id != network_id {
        return Err(format!(
            "Private key is bound to network_id `{}`, but call signing requested network_id `{network_id}`",
            key.network_id
        ));
    }

    let abi = fs::read(options.abi)
        .map_err(|e| format!("Failed to read ABI {}: {e}", options.abi.display()))?;
    let manifest = fs::read(options.manifest).map_err(|e| {
        format!(
            "Failed to read manifest {}: {e}",
            options.manifest.display()
        )
    })?;
    let abi_hash = sha256_array(&abi);
    validate_manifest_policy_for_call(&manifest, &abi_hash, options.chain, &network_id)?;

    let method_selector = method_selector_from_abi(&abi, options.method)?;
    let encoded_args = canonical_json_args(options.args, "Call")?;
    let encoded_args_hash = sha256_array(&encoded_args);
    let contract_address = parse_synq_address(options.contract)?;

    let public_key_bytes = hex::decode(&key.public_key_hex).map_err(|e| {
        format!(
            "Invalid public_key_hex in {}: {e}",
            options.private_key.display()
        )
    })?;
    let private_key_bytes = hex::decode(&key.private_key_hex).map_err(|e| {
        format!(
            "Invalid private_key_hex in {}: {e}",
            options.private_key.display()
        )
    })?;
    let public_key = SynQPublicKey::new(public_key_bytes);
    let signer_address = derive_synq_address(
        &public_key,
        AlgorithmId::MlDsa87,
        &NetworkId(network_id.clone()),
    )
    .map_err(|e| format!("aegis-pqsynq address derivation failed: {e}"))?;
    if signer_address.to_execution_signer_id() != key.address {
        return Err(
            "Private key file public key does not derive to its recorded SynQ address".to_string(),
        );
    }

    let payload_hash = hash_contract_call_body(
        contract_address.as_bytes(),
        &method_selector,
        &encoded_args_hash,
        signer_address.as_bytes(),
    );
    let signing_payload = SynQSigningPayload {
        domain_tag: DomainTag::SynqContractCallV1,
        chain_id: ChainId(options.chain),
        network_id: NetworkId(network_id.clone()),
        protocol_version: 1,
        algorithm_id: AlgorithmId::MlDsa87,
        signature_purpose: SignaturePurpose::ContractCall,
        nonce: options.nonce,
        not_before_unix: options.not_before_unix,
        expiration_unix: options.expiration_unix,
        signer_address,
        payload_hash,
    };
    let canonical = canonicalize_signing_payload(&signing_payload)
        .map_err(|e| format!("aegis-pqsynq canonical call payload failed: {e}"))?;
    let signature = Sign::mldsa87()
        .detached_sign(&canonical, &private_key_bytes)
        .map_err(|e| format!("aegis-pqsynq ML-DSA-87 call signing failed: {e}"))?;
    let envelope = ContractCallEnvelope {
        signing_payload,
        public_key,
        signature: SynQSignature::new(signature),
        contract_address,
        method_selector,
        encoded_args_hash,
    };

    let context = VerificationContext {
        chain_id: ChainId(options.chain),
        network_id: NetworkId(network_id.clone()),
        now_unix: options.not_before_unix,
        policy: pqsynq::SynQSecurityPolicy::testnet_1266_policy(),
    };
    AegisSynQVerifier::testnet_1266()
        .verify_contract_call(&envelope, &context)
        .map_err(|e| {
            format!(
                "aegis-pqsynq call self-verification failed: {} ({e})",
                e.code()
            )
        })?;

    write_json_file(options.output, &envelope, options.force, false)?;
    println!("✓ Signed SynQ call envelope through aegis-pqsynq");
    println!("envelope={}", options.output.display());
    println!("domain=SYNQ_CONTRACT_CALL_V1");
    println!("algorithm=ML-DSA-87");
    println!("chain_id={}", options.chain);
    println!("network_id={network_id}");
    println!("method={}", options.method);
    println!("method_selector=0x{}", hex::encode(method_selector));
    println!("args_hash={}", hex::encode(encoded_args_hash));
    println!(
        "contract={}",
        envelope.contract_address.to_execution_signer_id()
    );
    println!("signer={}", key.address);
    println!("payload_hash={}", hex::encode(payload_hash));
    Ok(())
}

